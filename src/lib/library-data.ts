export function localQuiz(topic: string): QuizPayload {
  const t = (topic || "").trim();
  if (LOCAL_QUIZZES[t]) return LOCAL_QUIZZES[t];
  const aliases: [RegExp, string][] = [
    [/شیمی|شيمی|chemistry/i, "شیمی"],
    [/زیست|biology|سلول/i, "زیست‌شناسی"],
    [/فیزیک|physics/i, "فیزیک"],
    [/ریاض|math/i, "ریاضی"],
    [/فارسی|ادبیات|شعر/i, "فارسی"],
    [/عربی/i, "عربی"],
    [/انگلیسی|english/i, "انگلیسی"],
    [/تاریخ|history/i, "تاریخ"],
    [/جغراف|geography/i, "جغرافیا"],
    [/علوم/i, "علوم"],
    [/کنکور|نهایی|نهائی/i, "کنکور و نهایی"],
  ];
  for (const [re, key] of aliases) {
    if (re.test(t) && LOCAL_QUIZZES[key]) return LOCAL_QUIZZES[key];
  }
  return {
    topic: t || "عمومی",
    questions: LOCAL_QUIZZES["اطلاعات عمومی"]?.questions || LOCAL_QUIZZES["علوم"].questions,
  };
}

